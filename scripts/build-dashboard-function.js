// Builds dashboard-function/index.tsx (a single-file Railway Function) from dashboard-standalone/*.
// Usage: node scripts/build-dashboard-function.js
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "dashboard-standalone");
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8");

const assets = { html: read("index.html"), css: read("app.css"), js: read("app.js"), svg: read("favicon.svg") };
for (const [name, text] of Object.entries(assets)) {
  if (text.includes("`") || text.includes("${")) {
    throw new Error(`dashboard-standalone asset (${name}) contains a backtick or \${ and cannot be embedded safely`);
  }
}

const out = `import { Hono } from "hono";

// DANTI dashboard: a no-build static site served by one Railway Function.
// GENERATED by scripts/build-dashboard-function.js from dashboard-standalone/. Edit those files, not this one.
const HTML = String.raw\`${assets.html}\`;
const CSS = String.raw\`${assets.css}\`;
const JS = String.raw\`${assets.js}\`;
const SVG = String.raw\`${assets.svg}\`;

// The page keeps the access key in browser storage, so lock it down: no inline scripts, no framing,
// and it may only talk to the DANTI API.
const API_ORIGIN = Bun.env.API_ORIGIN ?? "https://danti-api-production.up.railway.app";
const SECURITY = {
  "Cache-Control": "no-store",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "no-referrer",
  "X-Frame-Options": "DENY",
  "Content-Security-Policy":
    "default-src 'none'; script-src 'self'; style-src 'self' https://fonts.googleapis.com; " +
    "font-src https://fonts.gstatic.com; img-src 'self' data:; connect-src " + API_ORIGIN + "; " +
    "base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
};
const send = (body: string, type: string) =>
  new Response(body, { headers: { ...SECURITY, "Content-Type": type } });

const app = new Hono();
app.get("/", () => send(HTML, "text/html; charset=utf-8"));
app.get("/app.css", () => send(CSS, "text/css; charset=utf-8"));
app.get("/app.js", () => send(JS, "text/javascript; charset=utf-8"));
app.get("/favicon.svg", () => send(SVG, "image/svg+xml"));
app.get("/health", (c) => c.json({ status: "ok" }));

export default {
  port: Number(Bun.env.PORT ?? 8000),
  fetch: app.fetch,
};
`;
fs.writeFileSync(path.join(__dirname, "..", "dashboard-function", "index.tsx"), out);
console.log("wrote dashboard-function/index.tsx (" + out.length + " bytes)");
